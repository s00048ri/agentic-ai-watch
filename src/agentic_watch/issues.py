"""GitHub issue forms for proposing organisations and leads, and turning them into ledger changes.

The form files in .github/ISSUE_TEMPLATE are generated from the configuration
(`agentic-watch issue-templates`) so the drop-down options always match the vocabularies.
"""

from __future__ import annotations

import datetime as dt
import re
from dataclasses import dataclass
from typing import Any, get_args

import yaml

from .config import EcosystemRole, InclusionReason, LeadRoute, OrgType, Project, Size
from .discover import discover
from .fetch import Fetcher
from .ledger_ops import add_candidate, add_organisation, slugify

TEMPLATE_DIR = ".github/ISSUE_TEMPLATE"
NO_RESPONSE = "_No response_"


@dataclass
class Field:
    id: str
    label: str
    kind: str  # input | textarea | dropdown
    required: bool = False
    description: str = ""
    options: tuple[str, ...] = ()


def org_fields(project: Project) -> list[Field]:
    vocab = project.taxonomy.vocabularies
    return [
        Field("name", "Organisation name (English)", "input", True),
        Field("name_local", "Name in the local language", "input"),
        Field("home_url", "Home page URL", "input", True, "The organisation's own website."),
        Field("domains", "Domains accepted as sources", "input", True, "Comma-separated, e.g. example.com"),
        Field(
            "pages",
            "Pages to watch",
            "textarea",
            False,
            "Optional. One URL per line on the organisation's own site (newsroom, AI policy page, reports). "
            "RSS feeds and sitemaps are also looked up automatically from the home page.",
        ),
        Field("org_type", "Organisation type", "dropdown", True, options=get_args(OrgType)),
        Field(
            "ecosystem_role", "Role in the AI ecosystem", "dropdown", True, options=get_args(EcosystemRole)
        ),
        Field("sector", "Sector", "dropdown", True, options=tuple(t.id for t in vocab["sectors"])),
        Field("region", "Region", "dropdown", True, options=tuple(t.id for t in vocab["regions"])),
        Field("size", "Size", "dropdown", True, options=get_args(Size)),
        Field(
            "inclusion_reason", "Reason for inclusion", "dropdown", True, options=get_args(InclusionReason)
        ),
        Field("notes", "Notes for the reviewer", "textarea"),
    ]


def lead_fields() -> list[Field]:
    routes = tuple(r for r in get_args(LeadRoute) if r != "official-mention")
    return [
        Field("name", "Organisation name", "input", True),
        Field("lead_route", "Lead route", "dropdown", True, options=routes),
        Field(
            "lead_detail",
            "Lead detail",
            "textarea",
            True,
            "Where the lead came from (no confidential information).",
        ),
        Field("official_url", "Page on the organisation's own site (if known)", "input"),
    ]


KINDS = {
    "organisation": (
        "add-organisation.yml",
        "Propose an organisation",
        "add-organisation",
        "[Organisation] ",
    ),
    "lead": ("candidate-lead.yml", "Suggest a candidate lead", "candidate-lead", "[Lead] "),
}


def _form(project: Project, kind: str) -> dict[str, Any]:
    _file, name, label, title = KINDS[kind]
    fields = org_fields(project) if kind == "organisation" else lead_fields()
    body: list[dict[str, Any]] = [
        {
            "type": "markdown",
            "attributes": {
                "value": "This repository is public: do not include confidential information. "
                "A pull request is created from this form for review before anything changes."
            },
        }
    ]
    for f in fields:
        attrs: dict[str, Any] = {"label": f.label}
        if f.description:
            attrs["description"] = f.description
        if f.options:
            attrs["options"] = list(f.options)
        body.append(
            {"type": f.kind, "id": f.id, "attributes": attrs, "validations": {"required": f.required}}
        )
    return {"name": name, "description": name, "title": title, "labels": [label], "body": body}


def render_templates(project: Project) -> dict[str, str]:
    header = "# Generated by `agentic-watch issue-templates` from config/. Do not edit by hand.\n"
    out = {
        f"{TEMPLATE_DIR}/{KINDS[k][0]}": header
        + yaml.safe_dump(_form(project, k), sort_keys=False, allow_unicode=True)
        for k in KINDS
    }
    out[f"{TEMPLATE_DIR}/config.yml"] = header + "blank_issues_enabled: true\n"
    return out


def write_templates(project: Project, check: bool = False) -> list[str]:
    """Write the issue forms. With check=True, write nothing and return the files that are out of date."""
    stale = []
    for rel, text in render_templates(project).items():
        path = project.path(rel)
        if path.exists() and path.read_text(encoding="utf-8") == text:
            continue
        stale.append(rel)
        if not check:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
    return stale


def parse_issue_body(body: str, fields: list[Field]) -> dict[str, str | None]:
    """Parse the Markdown GitHub renders for an issue form ("### Label" sections)."""
    sections: dict[str, str] = {}
    for m in re.finditer(r"^### (.+?)\s*\n(.*?)(?=^### |\Z)", body, re.S | re.M):
        sections[m.group(1).strip()] = m.group(2).strip()
    out: dict[str, str | None] = {}
    for f in fields:
        value = sections.get(f.label, "").strip()
        out[f.id] = None if value in ("", NO_RESPONSE) else value
    return out


class IssueError(ValueError):
    pass


def _required(values: dict[str, str | None], fields: list[Field]) -> None:
    missing = [f.label for f in fields if f.required and not values.get(f.id)]
    if missing:
        raise IssueError("Missing: " + ", ".join(missing))


def apply_organisation_issue(
    project: Project, body: str, number: int, today: dt.date, fetcher: Fetcher | None
) -> str:
    """Add the proposed organisation to ledger/organisations.yaml. Returns the new organisation id."""
    fields = org_fields(project)
    v = parse_issue_body(body, fields)
    _required(v, fields)
    assert v["name"] and v["home_url"] and v["domains"]
    watch_points: list[dict[str, Any]] = []
    if fetcher is not None:
        for s in discover(fetcher, v["home_url"]):
            if "error" not in s:
                watch_points.append(
                    {k: s[k] for k in ("type", "url", "method", "feed_url", "language", "frequency")}
                )
    for line in (v.get("pages") or "").splitlines():
        url = line.strip().strip("-* ").strip()
        if url.startswith("http"):
            watch_points.append({"type": "newsroom", "url": url, "method": "manual", "frequency": "weekly"})
    for wp in watch_points:
        wp["verified"] = False  # a person confirms each URL when reviewing the pull request
    org = {
        "id": slugify(v["name"]),
        "name": v["name"],
        "name_local": v.get("name_local"),
        "domains": [d.strip() for d in v["domains"].split(",") if d.strip()],
        "org_type": v["org_type"],
        "ecosystem_role": v["ecosystem_role"],
        "sector": v["sector"],
        "region": v["region"],
        "size": v["size"],
        "inclusion_reason": v["inclusion_reason"],
        "lead_source": f"issue #{number}",
        "status": "active",
        "added": today.isoformat(),
        "last_reviewed": today.isoformat(),
        "watch_points": watch_points,
    }
    path = project.path("ledger/organisations.yaml")
    text = path.read_text(encoding="utf-8") if path.exists() else None
    path.write_text(add_organisation(text, org, project.taxonomy), encoding="utf-8")
    return str(org["id"])


def apply_lead_issue(project: Project, body: str, number: int, today: dt.date) -> str:
    fields = lead_fields()
    v = parse_issue_body(body, fields)
    _required(v, fields)
    cand = {
        "name": v["name"],
        "lead_route": v["lead_route"],
        "lead_detail": f"{v['lead_detail']} (issue #{number})",
        "official_confirmation_url": v.get("official_url"),
    }
    path = project.path("ledger/candidates.yaml")
    text = path.read_text(encoding="utf-8") if path.exists() else None
    path.write_text(add_candidate(text, cand, today), encoding="utf-8")
    return str(v["name"])
